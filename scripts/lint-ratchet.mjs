#!/usr/bin/env node
/**
 * ESLint ratchet: the lint debt in app/, components/ and lib/ may shrink but
 * never grow.
 *
 * ESLint already reports 411 problems in these three folders (302 errors, 109
 * warnings; measured 2026-10-13), so `npm run lint` always fails, nobody runs
 * it, and CI cannot gate on it -- which means a new problem lands as silently
 * as an old one sits. This counts what ESLint reports per file and
 * rule, compares it with the committed baseline, and fails on any count that
 * went up. Counts that went down pass, with the command that locks them in.
 *
 *   npm run lint:ratchet                 check against the baseline
 *   npm run lint:ratchet -- --update     rewrite the baseline from this tree
 *
 * --update refuses when any RULE's total went up, so it cannot be used to wave
 * new debt through. It does accept counts moving between files with the
 * total unchanged -- a rename, or code moved into a new module -- which the
 * check itself reports as an increase in the receiving file.
 *
 * Errors and warnings both count: the question is whether there is more to
 * fix than before, not how loudly ESLint says it.
 */
import { ESLint } from "eslint";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { relative, sep } from "node:path";

const TARGETS = ["app", "components", "lib"];
const BASELINE = "scripts/lint-ratchet.baseline.json";
const NO_RULE = "(no rule)";

const args = process.argv.slice(2);
const update = args.includes("--update");
const unknown = args.filter((a) => a !== "--update");
if (unknown.length) {
  console.error(`lint-ratchet: unknown argument(s): ${unknown.join(" ")}\nusage: node scripts/lint-ratchet.mjs [--update]`);
  process.exit(2);
}

if (!update && !existsSync(BASELINE)) {
  console.error(`lint-ratchet: no baseline at ${BASELINE}. Create it with: npm run lint:ratchet -- --update`);
  process.exit(2);
}

const started = Date.now();
const eslint = new ESLint({ cwd: process.cwd() });
const results = await eslint.lintFiles(TARGETS);

/** { file: { rule: count } } plus the locations, for the failure report. */
const current = {};
const where = {};
for (const r of results) {
  if (!r.messages.length) continue;
  const file = relative(process.cwd(), r.filePath).split(sep).join("/");
  for (const m of r.messages) {
    const rule = m.ruleId ?? NO_RULE;
    current[file] ??= {};
    current[file][rule] = (current[file][rule] ?? 0) + 1;
    (where[`${file}\0${rule}`] ??= []).push(`${file}:${m.line ?? 0}:${m.column ?? 0}  ${m.message}`);
  }
}

function totals(files) {
  const t = {};
  for (const rules of Object.values(files)) for (const [rule, n] of Object.entries(rules)) t[rule] = (t[rule] ?? 0) + n;
  return t;
}

function sorted(obj) {
  return Object.fromEntries(
    Object.keys(obj)
      .sort()
      .map((k) => [k, obj[k] && typeof obj[k] === "object" ? sorted(obj[k]) : obj[k]]),
  );
}

function write(files) {
  const body = {
    _comment:
      "Generated by scripts/lint-ratchet.mjs -- do not raise a count by hand. Counts may only go down; run `npm run lint:ratchet -- --update` after fixing lint problems.",
    eslint: ESLint.version,
    targets: TARGETS,
    totals: sorted(totals(files)),
    files: sorted(files),
  };
  writeFileSync(BASELINE, JSON.stringify(body, null, 2) + "\n");
}

const sum = (t) => Object.values(t).reduce((a, b) => a + b, 0);
const secs = ((Date.now() - started) / 1000).toFixed(1);
const nowTotals = totals(current);

if (!existsSync(BASELINE)) {
  write(current);
  console.log(`lint-ratchet: wrote ${BASELINE} -- ${sum(nowTotals)} problems in ${Object.keys(current).length} files (${secs}s).`);
  process.exit(0);
}

const base = JSON.parse(readFileSync(BASELINE, "utf8"));
const baseFiles = base.files ?? {};
const baseTotals = totals(baseFiles);

if (base.eslint && base.eslint !== ESLint.version) {
  console.error(
    `lint-ratchet: note -- the baseline was taken with ESLint ${base.eslint}, this is ${ESLint.version}. ` +
      "A new ESLint can report differently; if the counts moved for that reason alone, update the baseline in the same commit as the upgrade.",
  );
}

const ruleRises = Object.keys(nowTotals)
  .filter((rule) => nowTotals[rule] > (baseTotals[rule] ?? 0))
  .map((rule) => `${rule}: ${baseTotals[rule] ?? 0} -> ${nowTotals[rule]}`);

if (update) {
  if (ruleRises.length) {
    console.error(
      "lint-ratchet: refusing to update -- these rules have MORE problems than the baseline:\n  " +
        ruleRises.join("\n  ") +
        "\nFix them first; the baseline only ever moves down.",
    );
    process.exit(1);
  }
  write(current);
  console.log(
    `lint-ratchet: baseline updated -- ${sum(baseTotals)} -> ${sum(nowTotals)} problems (${secs}s). Commit ${BASELINE}.`,
  );
  process.exit(0);
}

const rises = [];
const drops = [];
for (const file of new Set([...Object.keys(current), ...Object.keys(baseFiles)])) {
  const now = current[file] ?? {};
  const was = baseFiles[file] ?? {};
  for (const rule of new Set([...Object.keys(now), ...Object.keys(was)])) {
    const a = was[rule] ?? 0;
    const b = now[rule] ?? 0;
    if (b > a) rises.push({ file, rule, a, b });
    else if (b < a) drops.push({ file, rule, a, b });
  }
}

if (rises.length) {
  console.error(`lint-ratchet: FAILED -- new lint problems in ${rises.length} file/rule pair(s):\n`);
  for (const { file, rule, a, b } of rises) {
    console.error(`  ${file}  ${rule}  ${a} -> ${b}`);
    for (const loc of where[`${file}\0${rule}`] ?? []) console.error(`      ${loc}`);
  }
  console.error(
    "\nEvery problem in that file under that rule is listed; at least " +
      "one is new. Fix the new ones." +
      (ruleRises.length
        ? ""
        : "\nNo rule's total went up, so if this is code that MOVED (a rename, or a function split into a new file), " +
          "`npm run lint:ratchet -- --update` accepts it."),
  );
  process.exit(1);
}

if (drops.length) {
  const fixed = drops.reduce((n, d) => n + d.a - d.b, 0);
  console.log(
    `lint-ratchet: OK -- ${fixed} fewer problem(s) than the baseline (${sum(nowTotals)} now, ${sum(baseTotals)} recorded; ${secs}s).\n` +
      `Lock the improvement in so it cannot come back: npm run lint:ratchet -- --update, then commit ${BASELINE}.`,
  );
  process.exit(0);
}

console.log(`lint-ratchet: OK -- ${sum(nowTotals)} problems, same as the baseline (${secs}s).`);
