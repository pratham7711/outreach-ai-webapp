/**
 * Renders the captured CreatorCore surfaces into a reviewable markdown
 * catalogue: every control on every surface, plus the screen's text laid out in
 * reading order. The capture (cc-ui-inventory.mjs) is the observation; this is
 * the artefact a human or a PRD can actually read.
 *
 *   node scripts/creatorcore/cc-render-inventory.mjs > docs/CREATORCORE_UI_INVENTORY.md
 */
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

const OUT = path.join(import.meta.dirname, "out", "ui");
const SIDEBAR_X = 215; // Left nav repeats on every surface; fold it away once.

const files = readdirSync(OUT)
  .filter((f) => f.endsWith(".json") && f !== "index.json")
  .sort();

const order = [
  "campaigns", "campaign-overview", "campaign-creators", "campaign-drafts",
  "campaign-posts", "campaign-analytics", "campaign-financials",
  "campaign-documents", "campaign-settings", "activations", "calendar",
  "clients", "creators", "lists", "discovery", "trackers", "trackers-creators",
  "fan-pages", "payouts", "requests", "recipients", "connections", "settings",
];
const rank = (f) => {
  const i = order.indexOf(f.replace(".json", ""));
  return i === -1 ? 999 : i;
};
files.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));

console.log("# CreatorCore — UI inventory (observed)\n");
console.log(
  "Generated by `scripts/creatorcore/cc-render-inventory.mjs` from the capture in\n" +
    "`scripts/creatorcore/out/ui/`. Every control on every surface, as rendered to the\n" +
    "LKM reference account at 1600×1000. View-only capture: nothing was clicked except\n" +
    "navigation, and controls that write are marked **W** so they are never actioned by\n" +
    "accident.\n",
);
console.log(
  "Reading the tables: `x`/`y` are viewport coordinates, so they show the reading\n" +
    "order and column structure that Bubble's nested divs hide. The left nav occupies\n" +
    `x < ${SIDEBAR_X} on every surface and is omitted below except in its own section.\n`,
);

for (const file of files) {
  const d = JSON.parse(readFileSync(path.join(OUT, file), "utf8"));
  if (!Array.isArray(d.text) || !Array.isArray(d.controls)) {
    console.error(`skipping ${file}: captured by an older version of the script`);
    continue;
  }
  const body = d.controls.filter((c) => c.box.x >= SIDEBAR_X);
  const nav = d.controls.filter((c) => c.box.x < SIDEBAR_X);

  console.log(`\n---\n\n## ${d.surface}\n`);
  console.log(`\`${d.url}\`\n`);
  console.log(
    `${d.controls.length} controls (${body.length} in the content area, ${nav.length} in the nav) · ` +
      `${d.text.length} text runs · ${d.controls.filter((c) => c.mutates).length} that write\n`,
  );

  // The screen, in reading order, with headings called out by size.
  const rows = new Map();
  for (const t of d.text) {
    if (t.x < SIDEBAR_X) continue;
    const key = Math.round(t.y / 12);
    if (!rows.has(key)) rows.set(key, []);
    rows.get(key).push(t);
  }
  if (rows.size) {
    console.log("### What the screen says\n");
    console.log("```");
    for (const key of [...rows.keys()].sort((a, b) => a - b)) {
      const items = rows.get(key).sort((a, b) => a.x - b.x);
      const line = items
        .map((i) => (i.size >= 20 ? `${i.text} [${i.size}px/${i.weight}]` : i.text))
        .join("   ");
      console.log(`y=${String(items[0].y).padStart(5)}  ${line.slice(0, 170)}`);
    }
    console.log("```\n");
  }

  if (body.length) {
    console.log("### Controls\n");
    console.log("| | x | y | w×h | kind | label |");
    console.log("|---|---|---|---|---|---|");
    for (const c of body.sort((a, b) => a.box.y - b.box.y || a.box.x - b.box.x)) {
      const kind = [c.tag, c.role, c.type].filter(Boolean).join("/");
      const label = (c.label || "*(icon only)*").replace(/\|/g, "\\|").slice(0, 90);
      console.log(
        `| ${c.mutates ? "**W**" : ""} | ${c.box.x} | ${c.box.y} | ${c.box.w}×${c.box.h} | ${kind} | ${label} |`,
      );
    }
    console.log("");
  }
}
